const char16_t* UpperHalf(Encoding encoding) {
    switch (encoding) {
    case Encoding::Dos866: return kDos866;
    case Encoding::Windows1251: return kWindows1251;
    case Encoding::Koi8R: return kKoi8R;
    case Encoding::Utf8: break;
    }
    return nullptr;
}

// Обратные таблицы строятся один раз.
const std::unordered_map<char32_t, unsigned char>& Reverse(Encoding encoding) {
    static const std::array<std::unordered_map<char32_t, unsigned char>, 3> tables = [] {
        std::array<std::unordered_map<char32_t, unsigned char>, 3> result;
        const Encoding encodings[3] = {Encoding::Dos866, Encoding::Windows1251, Encoding::Koi8R};
        for (int t = 0; t < 3; t++) {
            const char16_t* half = UpperHalf(encodings[t]);
            for (int i = 0; i < 128; i++)
                if (half[i])
                    result[t].emplace(half[i], static_cast<unsigned char>(0x80 + i));
        }
        return result;
    }();
    return tables[static_cast<int>(encoding)];
}

