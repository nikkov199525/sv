char32_t ToUnicode(Encoding encoding, unsigned char byte) {
    if (byte < 0x80)
        return byte;
    const char16_t* half = UpperHalf(encoding);
    if (!half || !half[byte - 0x80])
        return utf8::kReplacement;
    return static_cast<char32_t>(half[byte - 0x80]);
}

int FromUnicode(Encoding encoding, char32_t cp) {
    if (cp < 0x80)
        return static_cast<int>(cp);
    if (encoding == Encoding::Utf8)
        return -1;
    const auto& reverse = Reverse(encoding);
    const auto found = reverse.find(cp);
    return found == reverse.end() ? -1 : found->second;
}

std::u32string Decode(std::string_view bytes, Encoding encoding) {
    if (encoding == Encoding::Utf8) {
        if (bytes.substr(0, 3) == "\xEF\xBB\xBF")
            bytes.remove_prefix(3);
        return utf8::Decode(bytes);
    }
    std::u32string result;
    result.reserve(bytes.size());
    for (char c : bytes)
        result += ToUnicode(encoding, static_cast<unsigned char>(c));
    return result;
}

std::string ToUtf8(std::string_view bytes, Encoding encoding) {
    if (encoding == Encoding::Utf8)
        return std::string(bytes);
    return utf8::Encode(Decode(bytes, encoding));
}

std::string LegacyToUtf8(std::string_view bytes, Encoding legacy) {
    return utf8::IsValid(bytes) ? std::string(bytes) : ToUtf8(bytes, legacy);
}

